#!/usr/bin/env bash
#
# st-reports-update.sh — RUNTIME-ONLY build step (2026-08-31, user request):
# ingest a delivered ~/cloud/update.7z BEFORE anything parses. The archive is
# packed elsewhere with the SAME password st-reports-archive.sh generates
# (input/secrets/st-reports.pass) and carries fresh exports under the repo's
# own input/ layout. When the file exists:
#
#   1. unpack it (password from input/secrets/st-reports.pass),
#   2. copy the files of exactly these six directories onto the checkout's
#      same directories (existing files overwritten — a re-delivered export
#      replaces its older self, and the incremental parse manifests notice
#      the changed sizes and reparse):
#          input/acceptance/flow-manager/   input/production/flow-manager/
#          input/acceptance/server/         input/production/server/
#          input/acceptance/transfer/       input/production/transfer/
#   3. delete ~/cloud/update.7z — only after a fully successful copy.
#
# Nothing else in the archive is looked at: ip/, renames/, secrets/, the
# policy files and anything outside the six directories are never touched.
# No update.7z is the quiet no-op. A FAILURE (missing password file, wrong
# password, corrupt archive, none of the six directories inside) fails the
# build loudly and LEAVES the archive in place — building silently on stale
# inputs is worse than stopping; fix or remove ~/cloud/update.7z.
#
# Runs before the HAVE_ACC/HAVE_PROD detection in bin/build.sh, so an update
# delivering an environment's FIRST flow-manager exports enables that
# environment in the same build.
#
set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$SCRIPT_DIR/../.."

UPD="$HOME/cloud/update.7z"
[ -f "$UPD" ] || { echo "st-reports-update: no ~/cloud/update.7z — nothing to ingest." >&2; exit 0; }

command -v 7z >/dev/null 2>&1 || { echo "st-reports-update: 7z not found (brew install p7zip)." >&2; exit 1; }
PASSF="input/secrets/st-reports.pass"
[ -s "$PASSF" ] || { echo "st-reports-update: $PASSF missing — cannot unpack ~/cloud/update.7z (the password is generated by the archive step of a completed build; pack updates with that value)." >&2; exit 1; }
pass=$(cat "$PASSF")

tmp=$(mktemp -d "${TMPDIR:-/tmp}/stupd.XXXXXX")
trap 'rm -rf "$tmp"' EXIT

if ! 7z x -aoa -p"$pass" -o"$tmp" "$UPD" >/dev/null 2>&1; then
    echo "st-reports-update: could not unpack ~/cloud/update.7z (wrong password or corrupt archive) — the file stays; fix or remove it." >&2
    exit 1
fi

total=0
for d in input/acceptance/flow-manager input/acceptance/server input/acceptance/transfer \
         input/production/flow-manager input/production/server input/production/transfer; do
    # the archive may root its tree at input/ (the repo layout) or directly
    # at the environment directories — accept both
    src=""
    [ -d "$tmp/$d" ] && src="$tmp/$d"
    [ -z "$src" ] && [ -d "$tmp/${d#input/}" ] && src="$tmp/${d#input/}"
    [ -n "$src" ] || continue
    n=$(find "$src" -type f | wc -l | tr -d ' ')
    [ "$n" -gt 0 ] || continue
    mkdir -p "$d"
    cp -pR "$src"/. "$d"/
    total=$((total + n))
    echo "st-reports-update: $n file(s) -> $d/" >&2
done

if [ "$total" -eq 0 ]; then
    echo "st-reports-update: ~/cloud/update.7z holds NONE of the six input directories — the file stays; check its layout (expected input/<env>/{flow-manager,server,transfer}/...)." >&2
    exit 1
fi
rm -f "$UPD"
echo "st-reports-update: ingested $total file(s); removed ~/cloud/update.7z." >&2
